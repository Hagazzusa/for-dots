#!/usr/bin/env python3
"""Prepare local backup bytes only. Never invokes a remote or publication API."""
import argparse,datetime,json,shutil,sys
from pathlib import Path,PurePosixPath
from validate import audit,catalog_paths,png_chunks,png_text,PNG,PRIVATE_TOKENS,sha

def main():
 ap=argparse.ArgumentParser();ap.add_argument('--stage-dir',type=Path);args=ap.parse_args()
 root=Path(__file__).resolve().parents[1];stage=(args.stage_dir or root.with_name(root.name+'_backup_ready')).resolve()
 if stage.exists():raise SystemExit('Refusing to overwrite existing stage; choose a new --stage-dir.')
 if stage==root or root in stage.parents:raise SystemExit('Stage must be outside the source tree.')
 pre=audit(root,negative=True)
 if not pre['ok']:print(json.dumps(pre,indent=2));return 1
 cat=json.loads((root/'consolidation/study_catalog.json').read_text());paths=catalog_paths(cat);stage.mkdir(parents=True)
 rows=[]
 for rel in paths:
  src=root/rel;dst=stage/rel;dst.parent.mkdir(parents=True,exist_ok=True);before=src.read_bytes();after=before;transform='byte-identical'
  if src.suffix=='.png':
   chunks=png_chunks(before);kept=[];removed=0
   for kind,payload,raw in chunks:
    if kind in (b'tEXt',b'zTXt',b'iTXt',b'eXIf') and any(t in png_text(kind,payload) for t in PRIVATE_TOKENS):removed+=1
    else:kept.append(raw)
   if removed:
    after=PNG+b''.join(kept)
    original_pixels=b''.join(p for k,p,r in chunks if k==b'IDAT');new_pixels=b''.join(p for k,p,r in png_chunks(after) if k==b'IDAT')
    if original_pixels!=new_pixels:raise RuntimeError('PNG pixel stream changed: '+rel)
    transform=f'removed {removed} private path metadata chunk(s); IDAT byte stream unchanged'
  dst.write_bytes(after)
  rows.append({'path':rel,'size_bytes':len(after),'sha256':sha(after),'source_sha256':sha(before),'transformation':transform})
 report=audit(stage,negative=True)
 if not report['ok']:print(json.dumps(report,indent=2));return 1
 report_data=(json.dumps(report,indent=2)+'\n').encode();(stage/'VALIDATION_REPORT.json').write_bytes(report_data)
 rows.append({'path':'VALIDATION_REPORT.json','size_bytes':len(report_data),'sha256':sha(report_data),'transformation':'generated lightweight audit report'})
 new_prefixes=('mechanism/escape/','mechanism/axle_comparison/','mechanism/front_facade/','consolidation/')
 delta_rows=[dict(x) for x in rows if x['path']=='STUDY_INDEX.md' or x['path'].startswith(new_prefixes)]
 delta={'schema_version':1,'scope':'Only newly completed study/index/consolidation files; existing published art, nominal mechanism, sensitivity and cartridge files are excluded. Full local archive validation report/manifest are not a claim about remote bytes.','remote_action':'No remote changes are performed by this local preparation script.','files':delta_rows}
 delta_data=(json.dumps(delta,indent=2)+'\n').encode();(stage/'PUBLICATION_DELTA.json').write_bytes(delta_data)
 rows.append({'path':'PUBLICATION_DELTA.json','size_bytes':len(delta_data),'sha256':sha(delta_data),'transformation':'generated explicit new-file delta'})
 excluded=dict(cat['excluded_generated_files']);excluded['**/__pycache__/**']='Interpreter cache; not a source or result';excluded['**/preview_mesh.json']='Temporary mesh exchange regenerated by CAD builders'
 manifest={'schema_version':1,'created_utc':datetime.datetime.now(datetime.timezone.utc).isoformat(),'scope':'Exact full local archive payload, not current remote repository state. Manifest itself is excluded from its own hash list.','source_root_name':root.name,'publication_performed':False,'files':rows,'total_bytes':sum(x['size_bytes'] for x in rows),'excluded':excluded,'runtime_requirements':cat['runtime_requirements'],'publication_delta':'PUBLICATION_DELTA.json'}
 mf=stage/'BACKUP_MANIFEST.json';mf.write_text(json.dumps(manifest,indent=2)+'\n')
 final=audit(stage,manifest=mf,negative=True)
 if not final['ok']:print(json.dumps(final,indent=2));return 1
 print(json.dumps({'ok':True,'stage':str(stage),'cataloged_files':len(paths),'manifest_files':len(rows),'manifest_total_bytes':manifest['total_bytes'],'manifest_sha256':sha(mf.read_bytes()),'publication_delta_files':len(delta_rows),'sanitized_pngs':[x['path'] for x in rows if x.get('transformation','').startswith('removed')],'negative_tests':final['negative_tests'],'warnings':final['warnings']},indent=2));return 0
if __name__=='__main__':sys.exit(main())
